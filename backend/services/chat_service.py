"""One chat turn: save the question, stream the answer as StreamEvents, save the answer.

This is plain Python with no FastAPI or HTTP in it, so the route stays thin and the eval
runner (step 8) can call exactly the same code the UI uses.

Flow of `stream_reply`:
    1. get or create the conversation, save the user's message (committed before any LLM call,
       so the question survives even if the model fails)
    2. load recent history, render the versioned system prompt
    3. stream from the LLM gateway: each text delta becomes a TokenEvent
    4. save the assistant message with provenance (model, prompt, tokens, cost, latency)
    5. finish with DoneEvent, which is ALWAYS the last event, even after an error

If the client disconnects mid-answer (Stop button, closed tab), the partial answer is saved
with error_code="cancelled" before the cancellation is allowed to continue.
"""

import asyncio
import logging
import uuid
from collections.abc import AsyncIterator
from contextlib import aclosing
from datetime import date
from decimal import Decimal

import anyio
from pydantic import BaseModel, Field
from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from core.config import Settings
from core.events import (
    RETRYABLE_CODES,
    DoneEvent,
    ErrorEvent,
    StreamEvent,
    TokenEvent,
    Usage,
)
from core.llm import ChatMessage, Completion, LLMError, LLMGateway, TextDelta
from core.prompts import PromptRegistry, RenderedPrompt
from core.tracing import Span, Tracer
from models import Conversation, Message

logger = logging.getLogger(__name__)

TITLE_MAX_CHARS = 80


class ChatRequest(BaseModel):
    """Body of POST /api/chat."""

    conversation_id: uuid.UUID  # generated by the frontend for a new chat
    message: str = Field(min_length=1, max_length=8000)
    model_id: str | None = None  # None = the catalog's default chat model


class AnswerResult(BaseModel):
    """Result of a one-shot answer (no conversation). Used by the eval runner."""

    answer: str
    error_code: str | None
    completion: Completion | None
    prompt_ref: str
    trace_id: str | None


class ChatService:
    def __init__(
        self,
        gateway: LLMGateway,
        prompts: PromptRegistry,
        settings: Settings,
        session_factory: async_sessionmaker[AsyncSession],
        tracer: Tracer,
    ):
        self._gateway = gateway
        self._prompts = prompts
        self._settings = settings
        self._session_factory = session_factory
        self._tracer = tracer

    async def stream_reply(self, request: ChatRequest, model_id: str) -> AsyncIterator[StreamEvent]:
        """Public entry point. Guarantees the stream ends with `done`, whatever happens inside.

        Each turn is one Langfuse trace; its session id is the conversation id, so Langfuse's
        Sessions view replays a whole conversation turn by turn.
        """
        trace = self._tracer.start_trace(
            "chat_turn",
            input=request.message,
            session_id=str(request.conversation_id),
            metadata={"model_id": model_id},
        )
        try:
            # aclosing: if this stream is closed early, close the inner one too, right away
            # (otherwise it would only be cleaned up whenever the garbage collector gets to it).
            async with aclosing(self._stream_reply(request, model_id, trace)) as events:
                async for event in events:
                    yield event
        except Exception:
            # Anything unexpected (DB down, a bug): log the full traceback for us,
            # send the user a generic message (never internals), and still close cleanly.
            logger.exception("chat turn failed for conversation %s", request.conversation_id)
            trace.finish(error="internal error")
            yield ErrorEvent(
                code="internal", message="Something went wrong on our side.", retryable=True
            )
            yield DoneEvent(
                message_id=None, trace_id=trace.trace_id, trace_url=self._trace_url(trace)
            )

    async def _stream_reply(
        self, request: ChatRequest, model_id: str, trace: Span
    ) -> AsyncIterator[StreamEvent]:
        # A session opened HERE, inside the stream, not taken from the request: the response
        # keeps streaming after the route function returns, when request-scoped resources
        # may already be closed.
        async with self._session_factory() as session:
            conversation = await self._get_or_create_conversation(session, request)
            session.add(
                Message(conversation_id=conversation.id, role="user", content=request.message)
            )
            conversation.updated_at = func.now()
            await session.commit()
            history = await self._load_history(session, conversation.id)

        prompt = self._render_system_prompt()
        llm_messages = [ChatMessage(role="system", content=prompt.text), *history]

        answer_parts: list[str] = []
        completion: Completion | None = None
        error: ErrorEvent | None = None
        stream = self._gateway.stream_chat(
            model_id, llm_messages, trace=trace, name="chat", prompt_ref=prompt.ref
        )
        try:
            async with aclosing(stream) as chunks:
                async for chunk in chunks:
                    if isinstance(chunk, TextDelta):
                        answer_parts.append(chunk.text)
                        yield TokenEvent(text=chunk.text)
                    else:
                        completion = chunk
        except LLMError as err:
            logger.warning("LLM error [%s] for %s: %s", err.kind, err.model_id, err.detail)
            error = ErrorEvent(
                code=err.kind, message=err.message, retryable=err.kind in RETRYABLE_CODES
            )
        except (asyncio.CancelledError, GeneratorExit):
            # The client went away. Keep the partial answer, then let cancellation continue.
            # Shielded: inside a cancelled task, every await would otherwise be cancelled too.
            logger.info("client disconnected from conversation %s", request.conversation_id)
            trace.finish(output="".join(answer_parts) or None, error="cancelled by client")
            if answer_parts:
                with anyio.CancelScope(shield=True):
                    await self._save_assistant_message(
                        request.conversation_id, "".join(answer_parts), model_id, prompt,
                        None, "cancelled", trace.trace_id,
                    )  # fmt: skip
            raise

        answer = "".join(answer_parts)
        trace.finish(output=answer or None, error=error.message if error else None)
        message_id: uuid.UUID | None = None
        if answer:  # save complete answers, and partial ones cut off by an error
            message_id = await self._save_assistant_message(
                request.conversation_id,
                answer,
                model_id,
                prompt,
                completion,
                error.code if error else None,
                trace.trace_id,
            )

        if error:
            yield error
        yield DoneEvent(
            message_id=str(message_id) if message_id else None,
            usage=_usage(model_id, completion),
            prompt_ref=prompt.ref,
            trace_id=trace.trace_id,
            trace_url=self._trace_url(trace),
        )

    def _trace_url(self, trace: Span) -> str | None:
        return self._tracer.trace_url(trace.trace_id)

    async def _get_or_create_conversation(
        self, session: AsyncSession, request: ChatRequest
    ) -> Conversation:
        conversation = await session.get(Conversation, request.conversation_id)
        if conversation is None:
            first_line = request.message.strip().splitlines()[0]
            conversation = Conversation(
                id=request.conversation_id, title=first_line[:TITLE_MAX_CHARS]
            )
            session.add(conversation)
        return conversation

    async def _load_history(
        self, session: AsyncSession, conversation_id: uuid.UUID
    ) -> list[ChatMessage]:
        """The last N messages, oldest first: the model's short-term memory.

        Why a limit: every message is re-sent on every turn (the model API is stateless),
        so long chats cost more tokens and eventually overflow the context window.
        Phase 4 replaces this simple window with summarised memory.
        """
        rows = await session.scalars(
            select(Message)
            .where(
                Message.conversation_id == conversation_id,
                Message.role.in_(("user", "assistant")),
                Message.error_code.is_(None),  # skip answers that were cut off by an error
            )
            .order_by(Message.created_at.desc())
            .limit(self._settings.chat_history_limit)
        )
        return [ChatMessage(role=m.role, content=m.content) for m in reversed(rows.all())]

    async def answer(
        self,
        question: str,
        model_id: str,
        *,
        trace_name: str = "answer",
        session_id: str | None = None,
        tags: list[str] | None = None,
    ) -> AnswerResult:
        """Answer one question with the same system prompt, gateway and tracing as the chat,
        but with no history and nothing saved. The eval runner uses this, so evals measure
        what users get without filling the conversation list with test chats."""
        prompt = self._render_system_prompt()
        trace = self._tracer.start_trace(
            trace_name, input=question, session_id=session_id, tags=tags
        )
        messages = [
            ChatMessage(role="system", content=prompt.text),
            ChatMessage(role="user", content=question),
        ]
        parts: list[str] = []
        completion: Completion | None = None
        error_code: str | None = None
        try:
            async for chunk in self._gateway.stream_chat(
                model_id, messages, trace=trace, name="chat", prompt_ref=prompt.ref
            ):
                if isinstance(chunk, TextDelta):
                    parts.append(chunk.text)
                else:
                    completion = chunk
        except LLMError as err:
            error_code = err.kind
            logger.warning("answer failed [%s] for %s: %s", err.kind, model_id, err.detail)
        answer = "".join(parts)
        trace.finish(output=answer or None, error=error_code)
        return AnswerResult(
            answer=answer,
            error_code=error_code,
            completion=completion,
            prompt_ref=prompt.ref,
            trace_id=trace.trace_id,
        )

    def _render_system_prompt(self) -> RenderedPrompt:
        return self._prompts.render(
            "chat_system",
            assistant_name=self._settings.assistant_name,
            today=date.today().isoformat(),
        )

    async def _save_assistant_message(
        self,
        conversation_id: uuid.UUID,
        answer: str,
        model_id: str,
        prompt: RenderedPrompt,
        completion: Completion | None,
        error_code: str | None,
        trace_id: str | None,
    ) -> uuid.UUID:
        async with self._session_factory() as session:
            message = Message(
                conversation_id=conversation_id,
                role="assistant",
                content=answer,
                model_id=model_id,
                prompt_ref=prompt.ref,
                error_code=error_code,
                trace_id=trace_id,
            )
            if completion:
                message.input_tokens = completion.input_tokens
                message.output_tokens = completion.output_tokens
                message.cost_usd = (
                    Decimal(str(completion.cost_usd)) if completion.cost_usd is not None else None
                )
                message.latency_ms = completion.latency_ms
                message.time_to_first_token_ms = completion.time_to_first_token_ms
            session.add(message)
            conversation = await session.get(Conversation, conversation_id)
            if conversation:
                conversation.updated_at = func.now()
            await session.commit()
            return message.id


def _usage(model_id: str, completion: Completion | None) -> Usage | None:
    if completion is None:
        return None
    return Usage(
        model_id=model_id,
        input_tokens=completion.input_tokens,
        output_tokens=completion.output_tokens,
        cost_usd=completion.cost_usd,
        latency_ms=completion.latency_ms,
        time_to_first_token_ms=completion.time_to_first_token_ms,
    )
