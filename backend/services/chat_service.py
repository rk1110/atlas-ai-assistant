class ImageInput(BaseModel):
    """An image attached in the browser (Phase 6). The declared type is only a hint: the real
    type is read from the bytes (core/images.py)."""

    media_type: str = Field(max_length=64)
    data: str = Field(max_length=30_000_000)  # base64; the MB limit is checked after decoding


class ChatRequest(BaseModel):
    """Body of POST /api/chat."""

    conversation_id: uuid.UUID  # generated by the frontend for a new chat
    message: str = Field(min_length=1, max_length=8000)
    model_id: str | None = None  # None = the catalog's default chat model
    # "Try again" after a failed answer: the question is already saved (it's saved before the
    # model is called), so answer it again instead of storing a second copy.
    retry: bool = False
    images: list[ImageInput] = Field(default_factory=list, max_length=10)  # Phase 6


# A checked image: its raw bytes (for the database) and the part sent to the model.
DecodedImage = tuple[bytes, ImagePart]


class ApprovalDecision(BaseModel):
    """Body of POST /api/chat/approval: the human's answer to an approval card."""

    conversation_id: uuid.UUID
    approval_id: str = Field(min_length=3, max_length=200)
    decision: Literal["approve", "reject"]
    # Set when the human edited the action on the card; validated against the tool's schema.
    args: dict[str, Any] | None = None
    model_id: str | None = None


class AnswerResult(BaseModel):
    """Result of a one-shot answer (no conversation). Used by the eval runner."""

    answer: str
    error_code: str | None
    completion: Completion | None
    prompt_ref: str
    trace_id: str | None
    search_query: str = ""  # what retrieval searched for (the rewrite, for follow-ups)
    chunks: list[Chunk] = Field(default_factory=list)  # what retrieval found, best first
    citations: list[CitationEvent] = Field(default_factory=list)  # what the answer cited


